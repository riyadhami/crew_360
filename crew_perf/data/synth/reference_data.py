"""Reference data transcribed from the dev Snowflake extracts.

A master table is what makes a code mean anything. `LEAVE_TYPE_ID = 10` is
uninterpretable until `M_LMS_LEAVE_TYPE` says it is LWP — so inventing
plausible-looking mappings is not a neutral simplification, it produces a system
that works perfectly against fiction and breaks on contact with the warehouse.
What a hand-written seed got wrong is the shape of error this module prevents:

    id  guessed               actually
    ──  ────────────────────  ─────────────────────────────
     3  Pending               CarryForword   (a balance state, not a request state)
     4  Withdrawn             Earned         (likewise)
     7  LWP                   TRAINING       (LWP is id 10)

**These are values, not an input.** The extracts themselves are dev CSV dumps and
are deliberately not carried in the repo or read at runtime: a directory that
must be present for `crewperf synth` to produce correct codes is a dependency
that fails silently when it is absent — the generator still runs, and every
lookup quietly reverts to a guess. Transcribing the values here makes the
reference part of the code, so it is reviewable in a diff, cannot go missing,
and cannot differ between two checkouts.

Only reference tables are here. Transactional rows — assessments, leave requests,
flights — are still generated, because the whole design depends on them
descending from a hidden competence profile that real data cannot supply.

## What was applied on the way in
- Labels are trimmed. The real `LWP` row carries `'Unpaid Leave '` with a
  trailing space; codes are left exactly as the warehouse spells them.
- `PEP_QUESTIONS` holds the *live, scored, deduplicated* bank: inactive rows and
  categories dropped, the same question merged across the templates that ask it
  (keeping the highest mark per role column), and the 14 asked-but-unscored rows
  removed. 345 extract rows reduce to the 41 distinct questions below.
- `PEP_CATEGORIES` is one row per distinct live category code, in form order.

## Facts worth knowing before changing anything here
- Three leave types are unpaid — LWP, NAF ("Unpaid Leave (UnApproved)") and ELWP
  ("Emergency Unpaid Leave"). Anything matching "unpaid" must say which it means.
- `LEAVE_STATUS_TYPES` mixes request states with balance states (`CarryForword`,
  `Earned`, `Expire`) and nothing in the schema separates them, which is why
  scorers match on the status *name* rather than assuming a range of ids.
- `ISSUE_CATEGORIES` really does ship two rows with a null name and no GUID.
  They are kept: that is a fact about the source, and dropping them here would
  hide a data-quality problem the agents should see.
- The grade scale is A/B/C, and C is the lowest *passing* grade — there is no
  failing band. Marks are fractional and each template's own mark column totals
  exactly 100.00; whole numbers cannot reproduce that.
"""

